// Presentation replay of real recorded answer rows. No model/extraction call.
// The prior capture is rendered innerText: restore its list markers/headings
// explicitly here, not in production. This is not a new live-answer success.
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
const capture = readFileSync(resolve('../docs/ui-workspace/evidence/live-table19/19__vol2__094.answer.txt'), 'utf8');
const lines = capture.split('\n');
const rows = lines.filter(line => line.startsWith('MARK:'));
assert.equal(rows.length, 5);
const title = lines[lines.indexOf('ANSWER') + 1];
const columnHeading = lines.find(line => line.startsWith('MARK –'));
const text = `**${title}**\n\n**${columnHeading}**\n\n${rows.map(row => '- ' + row).join('\n')}`;
const expected = rows.map(row => row.split(' · ').map(chunk => {
  const colon = chunk.indexOf(': ');
  return [chunk.slice(0, colon), chunk.slice(colon + 2)];
}));
assert.ok(expected.every(row => row.length === 35));
const out = process.env.OT_ANSWER_OUT || '/tmp/ot-agent-answer';
mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.OT_BROWSER_PATH || undefined });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [], checks = [];
page.on('pageerror', error => errors.push(String(error)));
const check = (label, ok) => { assert.ok(ok, label); checks.push(label); console.log('ok', label); };
try {
  await page.goto(process.env.OT_UI_URL || 'http://127.0.0.1:5176');
  await page.locator('.workspace-body').waitFor();
  await page.evaluate(async () => {
    const { mountAgentHarness } = await import('/scripts/fixtures/ui-agent-harness.jsx');
    mountAgentHarness();
  });
  await page.evaluate(text => window.__uiRender({ thread: [{ role: 'assistant', text }], citations: [], takeoffRowCount: 0 }), text);
  const records = page.locator('[data-agent-answer-record]');
  await records.first().waitFor();
  await page.locator('[data-workspace-dock]').evaluate(el => { el.parentElement.style.width = '100vw'; });
  check('five recorded rows, no invented rows', await records.count() === 5);
  const actual = await records.evaluateAll(nodes => nodes.map(node => [...node.querySelectorAll('dl > div')].map(field => [field.querySelector('dt').textContent, field.querySelector('dd').textContent])));
  assert.deepEqual(actual, expected);
  check('all 175 field labels and values preserved exactly in original order', true);
  check('all row summaries fit in one answer viewport', await records.last().evaluate(el => el.getBoundingClientRect().bottom < document.querySelector('.agent-composer').getBoundingClientRect().top));
  await page.screenshot({ path: resolve(out, 'recorded-rows-overview.png') });
  await page.locator('[data-workspace-dock]').screenshot({ path: resolve(out, 'answer-overview.png') });
  await records.first().locator('summary').focus();
  await page.keyboard.press('Enter');
  check('keyboard opens row details', await records.first().getAttribute('open') !== null);
  await page.screenshot({ path: resolve(out, 'recorded-row-details.png') });
  await page.locator('[data-workspace-dock]').screenshot({ path: resolve(out, 'answer-details.png') });
  for (const width of [1280, 1440, 1920, 2560]) {
    await page.setViewportSize({ width, height: 900 });
    check(`${width}: dock fits viewport`, await page.locator('[data-workspace-dock]').evaluate(el => { const r = el.getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth; }));
    check(`${width}: answer fields stay inside dock`, await page.locator('.agent-answer-fields').first().evaluate(el => el.scrollWidth <= el.clientWidth));
    check(`${width}: composer remains visible`, await page.locator('.agent-composer').evaluate(el => el.getBoundingClientRect().bottom <= innerHeight));
  }
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.evaluate(() => document.documentElement.dataset.theme = 'dark');
  await page.screenshot({ path: resolve(out, 'recorded-row-hud.png') });
  // A deterministic citation is separate from the recorded rows, so the replay
  // cannot imply that a source linkage was generated by this test.
  const cite = { id: 'cite-1', sheet: 'test#1', bbox_px: [10, 20, 30, 40], row_key: 'AHU-1', column: 'CFM', value: '500' };
  await page.evaluate(cite => window.__uiRender({ citations: [cite], thread: [{ role: 'assistant', text: '- MARK: AHU-1 · CFM: 500 · NOTE: unchanged · STATUS: review' }] }), cite);
  await records.first().locator('summary').click();
  await page.locator('.agent-answer-fields button').first().click();
  assert.deepEqual(await page.evaluate(() => window.__uiCalls.pop()), ['onOpenCitation', cite]);
  check('field citation retains exact callback and bbox', true);
  check('no browser errors', errors.length === 0);
  writeFileSync(resolve(out, 'checks.json'), JSON.stringify({ provenance: 'Presentation replay of 175 fields from recorded live table19 answer; separate synthetic callback control', checks, errors }, null, 2));
} finally { await browser.close(); }
